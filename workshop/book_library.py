"""The book's hands as a SmallCards deal library (a .js file). No tkinter in here.

The library is generated: every export writes it afresh from the book, in book order,
so it is never edited by hand. Each entry is the hand's ordinary library entry
(storage.to_library_dict) with the three fields SmallCards' library table shows
taken from the hand's place in the book:

    name         "Hand 1: Basic Play" or "Training Hand 3"
    description  the hand's concept, or "Training: <chapter title>"
    reference    the hand code, e.g. "II.3.1" or "II.3.T3" (SmallCards' "Page" column)

Hands SmallCards cannot play yet (incomplete, no lead, ...) are left out and reported.
"""

import os
from datetime import datetime
from pathlib import Path

from .playtest import playtest_problems
from .storage import library_deals, library_entry_text, to_library_dict

HEADER = "// Generated by Palamedes"
# Libraries generated before the program was renamed start like this
OLD_HEADERS = ("// Generated by ConstructInstruct",)


def library_entries(project):
    """(entries, left_out): entries in book order; left_out is [(code, title, reason)]."""
    entries, left_out = [], []
    for section in project.book.sections:
        for chapter_id in section.chapters:
            chapter = project.chapters.get(chapter_id)
            if chapter is None:
                continue
            for slot in chapter.teaching() + chapter.training():
                deal = project.deals.get(slot.deal)
                code = project.hand_code(slot.deal)
                title = deal.author.title.strip() if deal else ""
                problems = ["its file is missing"] if deal is None else playtest_problems(deal)
                if problems:
                    left_out.append((code, title or slot.deal, "; ".join(problems)))
                    continue
                entry = to_library_dict(deal)
                label = project.hand_label(slot.deal)
                if slot.role == "hand":
                    entry["name"] = f"{label}: {title}" if title else label
                    entry["description"] = deal.author.concept.strip()
                else:
                    entry["name"] = label
                    entry["description"] = f"Training: {chapter.title}"
                entry["book"] = project.book.title
                entry["reference"] = code
                entries.append(entry)
    return entries, left_out


def library_text(project, entries, when=None):
    when = when or datetime.now().strftime("%Y-%m-%d %H:%M")
    head = (f"{HEADER} from the book \"{project.book.title}\" on {when}.\n"
            "// Do not edit this file: the next export replaces it. Change the book instead.\n")
    body = ",\n".join(library_entry_text(e) for e in entries)
    return f"{head}var libDeals = [\n{body}\n];\n" if entries else f"{head}var libDeals = [];\n"


def is_generated(path):
    """True if the file was written by this export (so it can be replaced without asking)."""
    try:
        with open(path, encoding="utf-8-sig") as f:
            return f.readline().startswith((HEADER,) + OLD_HEADERS)
    except FileNotFoundError:
        return True
    except (OSError, UnicodeDecodeError):
        return False


def default_library_path(project, folder):
    name = "".join(ch for ch in project.book.title if ch not in '\\/:*?"<>|').strip()
    return Path(folder) / f"{name or 'Book'}.js"


def export_library(project, path):
    """Write the book's library to path. Returns (number of hands, left_out).

    The text is checked to read back as exactly the entries before it replaces the file.
    """
    entries, left_out = library_entries(project)
    text = library_text(project, entries)
    if library_deals(text) != entries:
        raise ValueError("The library did not read back correctly; nothing was written")
    path = Path(path)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    return len(entries), left_out
