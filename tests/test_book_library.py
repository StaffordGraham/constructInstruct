import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from tests.test_book import PLAN, variant
from tests.test_compat import PROBE, SMALLCARDS_DEAL_JS
from workshop.book_import import new_project, plan_outline
from workshop.book_library import (default_library_path, export_library, is_generated,
                                   library_entries)
from workshop.storage import library_deals, read_library, to_library_dict


class BookLibraryTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.folder = Path(self.tmp.name)
        p = self.p = new_project(self.folder / "Book", "Learn Declarer Play", "Graham",
                                 plan_outline(PLAN))
        # chapter I.2 first in the book, then II.2 - placed out of order on purpose
        self.ruff = p.add_deal(variant(1))
        self.ruff.author.concept = "Ruff losers in dummy"
        self.ruff.checkpoints = [{"trick": 2, "seat": "N", "accept": [0]}]
        p.place(self.ruff.id, "ruffing-losers-in-dummy", "hand")
        self.training = p.add_deal(variant(2))
        p.place(self.training.id, "no-trump-contracts-keep-control", "training")
        self.nt = p.add_deal(variant(3))
        self.nt.author.concept = "Keep control"
        p.place(self.nt.id, "no-trump-contracts-keep-control", "hand")
        broken = p.add_deal(variant(4))
        broken.opening_lead = None
        p.place(broken.id, "ruffing-losers-in-dummy", "training")
        p.add_deal(variant(5))                                   # unplaced: not in the library
        p.save()

    def tearDown(self):
        self.tmp.cleanup()

    def test_entries_in_book_order_named_from_the_book(self):
        entries, left_out = library_entries(self.p)
        self.assertEqual([(e["name"], e["description"], e["reference"]) for e in entries], [
            ("Hand 1: Hand 3", "Keep control", "I.2.1"),
            ("Training Hand 1", "Training: No Trump Contracts Keep Control", "I.2.T1"),
            ("Hand 1: Hand 1", "Ruff losers in dummy", "II.2.1")])
        self.assertEqual(left_out, [("II.2.T1", "Hand 4",
                                     "Set an opening lead — SmallCards starts play with it")])
        self.assertTrue(all(e["book"] == "Learn Declarer Play" for e in entries))
        # everything else is the hand's own library entry, unchanged
        own = to_library_dict(self.ruff)
        for k in own.keys() - {"name", "description", "reference", "book"}:
            self.assertEqual(entries[2][k], own[k], k)
        self.assertEqual(self.ruff.author.title, "Hand 1")       # the hand itself is untouched

    def test_export_writes_a_library_smallcards_can_read(self):
        path = default_library_path(self.p, self.folder)
        self.assertEqual(path.name, "Learn Declarer Play.js")
        self.assertEqual(export_library(self.p, path)[0], 3)
        text, _ = read_library(path)
        self.assertTrue(text.startswith("// Generated by Palamedes"))
        self.assertEqual(library_deals(text), library_entries(self.p)[0])
        self.assertTrue(is_generated(path))

    def test_hand_made_libraries_are_recognised(self):
        own = self.folder / "dealLibrary.js"
        own.write_text("var libDeals = [];\n", encoding="utf-8")
        self.assertFalse(is_generated(own))
        self.assertTrue(is_generated(self.folder / "new.js"))     # nothing there yet
        old = self.folder / "old.js"                              # made before the rename
        old.write_text("// Generated by ConstructInstruct from the book\nvar libDeals = [];\n",
                       encoding="utf-8")
        self.assertTrue(is_generated(old))

    def test_empty_book(self):
        p = new_project(self.folder / "Empty", "Empty", outline=[])
        path = self.folder / "empty.js"
        self.assertEqual(export_library(p, path), (0, []))
        self.assertEqual(library_deals(path.read_text(encoding="utf-8")), [])

    @unittest.skipUnless(shutil.which("node"), "Node.js is not installed")
    @unittest.skipUnless(SMALLCARDS_DEAL_JS.exists(), "SmallCards is not next to this project")
    def test_smallcards_sees_the_book(self):
        path = self.folder / "book.js"
        export_library(self.p, path)
        result = subprocess.run(["node", str(PROBE), str(SMALLCARDS_DEAL_JS)],
                                input=json.dumps([path.read_text(encoding="utf-8")]),
                                capture_output=True, text=True, encoding="utf-8", check=True)
        seen, = json.loads(result.stdout)
        self.assertEqual([d["entry"]["reference"] for d in seen], ["I.2.1", "I.2.T1", "II.2.1"])
        ruff = seen[2]["deal"]
        self.assertEqual((ruff["name"], ruff["contract"], ruff["checkpoints"]),
                         ("Hand 1: Hand 1", "4 Hearts", self.ruff.checkpoints))
        self.assertEqual(sorted(ruff["north_cards"]), sorted(self.ruff.hand("N")))


if __name__ == "__main__":
    unittest.main()
